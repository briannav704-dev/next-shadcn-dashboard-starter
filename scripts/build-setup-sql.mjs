#!/usr/bin/env node
// Bundles every migration into supabase/setup.sql: one file to copy and paste
// into the Supabase SQL Editor (works from an iPad, no terminal needed).
// Usage: node scripts/build-setup-sql.mjs [--check]
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const dir = join(root, 'supabase', 'migrations');
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort();
const header = `-- ============================================================================
-- Kouture Life OS — complete database setup
-- GENERATED from supabase/migrations by scripts/build-setup-sql.mjs. Do not edit.
--
-- How to use: Supabase → SQL Editor → New query → paste this whole file → Run.
-- Run it ONCE on a new, empty project. Expected result: "Success. No rows returned".
-- ============================================================================
`;
const body = files
  .map((f) => `\n-- ─── ${f} ${'─'.repeat(Math.max(0, 70 - f.length))}\n\n${readFileSync(join(dir, f), 'utf8').trim()}\n`)
  .join('');
const output = `${header}${body}`;
const target = join(root, 'supabase', 'setup.sql');

// supabase/update.sql: only the migrations newer than the last one the owner's
// live database has, so an update is a single paste too. Bump APPLIED_THROUGH
// once she has run it.
const APPLIED_THROUGH = '20261128000001_ai_team.sql';
const pending = files.filter((f) => f > APPLIED_THROUGH);
const updateTarget = join(root, 'supabase', 'update.sql');
const updateOutput = `-- ============================================================================
-- Kouture Life OS — database update (${pending.length ? pending.join(', ') : 'nothing pending'})
-- GENERATED by scripts/build-setup-sql.mjs. Do not edit.
--
-- For a database that already ran setup.sql: Supabase → SQL Editor → New query
-- → paste this whole file → Run, once. A new project uses setup.sql instead.
-- ============================================================================
${pending.map((f) => `\n-- ─── ${f} ${'─'.repeat(Math.max(0, 70 - f.length))}\n\n${readFileSync(join(dir, f), 'utf8').trim()}\n`).join('')}`;

if (process.argv.includes('--check')) {
  const stale = [
    [target, output],
    [updateTarget, updateOutput]
  ].filter(([path, expected]) => readFileSync(path, 'utf8') !== expected);
  if (stale.length) {
    console.error('supabase/setup.sql or update.sql is out of date. Run: node scripts/build-setup-sql.mjs');
    process.exit(1);
  }
  console.log('supabase/setup.sql and update.sql are up to date');
} else {
  writeFileSync(target, output);
  writeFileSync(updateTarget, updateOutput);
  console.log(`Wrote supabase/setup.sql from ${files.length} migrations, update.sql from ${pending.length}`);
}
